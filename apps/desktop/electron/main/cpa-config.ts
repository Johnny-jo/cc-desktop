import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { isMap, isSeq, parseDocument } from "yaml";

export type CpaConfigApplyMode = "full" | "repair-panel";

function readConfig(source: string) {
  const doc = parseDocument(source);
  if (doc.errors.length || !isMap(doc.contents)) {
    // YAML diagnostics can contain credential values. Never include them here.
    throw new Error("CPA config must be a valid YAML mapping");
  }
  return doc;
}

function configPaths(doc: ReturnType<typeof readConfig>) {
  const v8 = doc.get("config-version") === 8 || doc.has("server") ||
    doc.has("management") || doc.has("access");
  return {
    server: v8 ? ["server"] : [],
    management: doc.has("management") || (v8 && !doc.has("remote-management"))
      ? ["management"] : ["remote-management"],
    // In v8 the top-level api-keys mapping contains UPSTREAM credentials.
    clientKeys: doc.hasIn(["access", "api-keys"]) || !isSeq(doc.get("api-keys", true))
      ? ["access", "api-keys"] : ["api-keys"],
    authDir: doc.hasIn(["oauth", "auth-dir"]) || v8
      ? ["oauth", "auth-dir"] : ["auth-dir"],
  };
}

export function applyCpaConfigDefaults(
  source: string,
  opts: { port: number; apiKey?: string | null; mode?: CpaConfigApplyMode },
): string {
  const doc = readConfig(source);
  const fields = configPaths(doc);
  let changed = false;
  const set = (keys: string[], value: unknown) => {
    if (JSON.stringify(doc.getIn(keys)) === JSON.stringify(value)) return;
    doc.setIn(keys, value);
    changed = true;
  };
  const management = fields.management;
  set([...management, "disable-control-panel"], false);
  // Ship a matching backend/panel pair instead of independently fetching latest.
  set([...management, "disable-auto-update-panel"], true);
  const secretPath = [...management, "secret-key"];
  const secret = doc.getIn(secretPath);
  const secretEmpty = secret == null || secret === "";
  if ((opts.mode ?? "full") === "repair-panel") {
    if (secretEmpty && opts.apiKey) set(secretPath, opts.apiKey);
    // A boot-time panel repair must preserve listener, auth-dir and all keys.
  } else {
    set([...fields.server, "host"], "127.0.0.1");
    set([...fields.server, "port"], opts.port);
    if (!doc.getIn(fields.authDir)) {
      set(fields.authDir, doc.get("auth-dir") || path.join(os.homedir(), ".cli-proxy-api"));
    }
    if (opts.apiKey) {
      set(fields.clientKeys, [opts.apiKey]);
      set(secretPath, opts.apiKey);
    }
  }
  return changed ? doc.toString() : source;
}

export function repairCpaManagementConfig(
  configPath: string,
  opts?: { apiKey?: string | null; port?: number },
): boolean {
  if (!configPath || !fs.existsSync(configPath)) return false;
  try {
    const source = fs.readFileSync(configPath, "utf8");
    const doc = readConfig(source);
    const keyNode = doc.getIn(configPaths(doc).clientKeys, true);
    const keys = isSeq(keyNode) ? keyNode.toJSON() : null;
    const existingKey = Array.isArray(keys) && typeof keys[0] === "string" ? keys[0] : null;
    const next = applyCpaConfigDefaults(source, {
      port: opts?.port ?? 8317,
      apiKey: opts?.apiKey ?? existingKey,
      mode: "repair-panel",
    });
    if (next === source) return false;
    fs.writeFileSync(configPath, next, "utf8");
    return true;
  } catch {
    return false;
  }
}

export function isPlaceholderCpaConfig(source: string): boolean {
  try {
    const doc = readConfig(source);
    const fields = configPaths(doc);
    const secret = doc.getIn([...fields.management, "secret-key"]);
    if (typeof secret === "string" && /^\$2[aby]\$/.test(secret)) return false;
    const keyNode = doc.getIn(fields.clientKeys, true);
    const keys = isSeq(keyNode) ? keyNode.toJSON() : null;
    return secret === "change-me" || (Array.isArray(keys) && keys.includes("change-me"));
  } catch {
    return false;
  }
}

